import type { Metadata } from "next";
import { localizedPath, type Locale } from "../config";

/** Canonical site origin for SEO. Set NEXT_PUBLIC_SITE_URL in production. */
export function seoSiteUrl(): string {
  const raw = (
    process.env.NEXT_PUBLIC_SITE_URL ||
    process.env.NEXT_PUBLIC_APP_URL ||
    ""
  ).trim();
  if (raw) return raw.replace(/\/+$/, "");
  // Placeholder until NEXT_PUBLIC_SITE_URL is set to the real origin.
  return "https://flowpilot.ai";
}

/** Full per-page <head> metadata: title, description, canonical, OG, hreflang. */
export function pageMeta(
  path: string,
  locale: Locale,
  title: string,
  description: string,
): Metadata {
  const url = seoSiteUrl();
  const ogImage = `${url}/opengraph-image`;
  return {
    title,
    description,
    alternates: {
      canonical: localizedPath(path, locale),
      languages: {
        en: localizedPath(path, "en"),
        ar: localizedPath(path, "ar"),
      },
    },
    openGraph: {
      title,
      description,
      url: localizedPath(path, locale),
      siteName: "FlowPilot AI",
      type: "website",
      images: [{ url: ogImage, width: 1200, height: 630, alt: "FlowPilot AI" }],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [ogImage],
    },
  };
}

/** Pick the SEO dictionary for a locale. */
export function seoT(locale: Locale) {
  return (locale === "ar" ? ar : en).seo;
}

